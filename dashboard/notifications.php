<?php
/** All in-app notifications for the current user (broadcast + personal), with read / unread state. */
require_once __DIR__ . '/../includes/bootstrap.php';
require_staff();

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    csrf_verify();
    $action = (string)post('action');
    $id = post_int('id', 0);
    if ($action === 'read' && $id) db_exec('UPDATE notifications SET is_read = 1 WHERE id = ? AND (user_id IS NULL OR user_id = ?)', [$id, user_id()]);
    if ($action === 'read_all') db_exec('UPDATE notifications SET is_read = 1 WHERE (user_id IS NULL OR user_id = ?) AND is_read = 0', [user_id()]);
    if ($action === 'clear_read' && is_super_admin()) db_exec('DELETE FROM notifications WHERE is_read = 1 AND created_at < DATE_SUB(NOW(), INTERVAL 30 DAY)');
    if (is_ajax()) json_ok('Done.');
    redirect('dashboard/notifications.php' . ($_GET ? '?' . http_build_query($_GET) : ''));
}

$filter = get('filter', 'all');
$type = get('type', '');
$where = ['(n.user_id IS NULL OR n.user_id = ?)']; $params = [user_id()];
if ($filter === 'unread') $where[] = 'n.is_read = 0';
if ($type) { $where[] = 'n.type = ?'; $params[] = $type; }
$w = implode(' AND ', $where);
$perPage = 30; $page = max(1, (int)get('page', 1));
$total = (int)db_value("SELECT COUNT(*) FROM notifications n WHERE $w", $params, 0);
$pages = max(1, (int)ceil($total / $perPage)); $page = min($page, $pages);
$rows = db_all("SELECT n.* FROM notifications n WHERE $w ORDER BY n.is_read, n.id DESC LIMIT ? OFFSET ?", array_merge($params, [$perPage, ($page - 1) * $perPage]));
$types = db_all('SELECT type, COUNT(*) c, SUM(is_read = 0) unread FROM notifications WHERE (user_id IS NULL OR user_id = ?) GROUP BY type ORDER BY type', [user_id()]);
$typeMeta = ['contract' => ['Contract expired', 'bi-file-earmark-x', 'danger'], 'contract_due' => ['Contract expiring', 'bi-file-earmark-text', 'warning'], 'retirement' => ['Retirement', 'bi-award', 'warning'],
    'lpr' => ['LPR', 'bi-calendar-check', 'info'], 'probation' => ['Probation', 'bi-hourglass-split', 'primary'], 'deputation' => ['Deputation', 'bi-box-arrow-in-left', 'purple'],
    'break' => ['Break in service', 'bi-exclamation-triangle', 'danger'], 'death' => ['Death in service', 'bi-heart', 'dark']];
$qs = fn(array $o = []) => 'dashboard/notifications.php?' . http_build_query(array_filter(array_merge($_GET, $o), fn($v) => $v !== '' && $v !== null));

$page_title  = 'Notifications';
$page_subtitle = 'System alerts generated by the daily checks and lifecycle events';
$active_menu = 'dashboard';
$breadcrumbs = ['Notifications' => null];
$page_actions = '<form method="post" class="d-inline">' . csrf_field() . '<input type="hidden" name="action" value="read_all"><button class="btn btn-outline-secondary btn-sm"><i class="bi bi-check2-all me-1"></i>Mark all read</button></form>'
    . (is_super_admin() ? '<form method="post" class="d-inline">' . csrf_field() . '<input type="hidden" name="action" value="clear_read"><button class="btn btn-outline-danger btn-sm" data-confirm="Delete read notifications older than 30 days?"><i class="bi bi-trash me-1"></i>Clear old</button></form>' : '');
require ROOT_PATH . '/includes/header.php';
?>
<div class="row g-3">
    <div class="col-lg-3">
        <div class="card">
            <div class="list-group list-group-flush side-filter">
                <a href="<?= url($qs(['filter' => 'all', 'type' => '', 'page' => 1])) ?>" class="list-group-item list-group-item-action <?= $filter === 'all' && !$type ? 'active' : '' ?>"><i class="bi bi-inbox me-2"></i>All</a>
                <a href="<?= url($qs(['filter' => 'unread', 'type' => '', 'page' => 1])) ?>" class="list-group-item list-group-item-action <?= $filter === 'unread' && !$type ? 'active' : '' ?>"><i class="bi bi-envelope me-2"></i>Unread</a>
                <?php foreach ($types as $t): $m = $typeMeta[$t['type']] ?? [ucfirst($t['type']), 'bi-bell', 'secondary']; ?>
                <a href="<?= url($qs(['filter' => 'all', 'type' => $t['type'], 'page' => 1])) ?>" class="list-group-item list-group-item-action d-flex align-items-center <?= $type === $t['type'] ? 'active' : '' ?>"><i class="bi <?= $m[1] ?> me-2"></i><?= e($m[0]) ?><span class="ms-auto badge text-bg-light border"><?= (int)$t['unread'] ?: '' ?></span></a>
                <?php endforeach; ?>
            </div>
        </div>
    </div>
    <div class="col-lg-9">
        <div class="card">
            <div class="card-header"><span class="card-title"><?= number_format($total) ?> notification<?= $total === 1 ? '' : 's' ?></span><span class="small text-muted">Page <?= $page ?> / <?= $pages ?></span></div>
            <?php if (!$rows): ?><div class="empty-state"><i class="bi bi-bell-slash"></i>No notifications here.</div><?php else: ?>
            <div class="list-group list-group-flush">
                <?php foreach ($rows as $n): $m = $typeMeta[$n['type']] ?? ['Alert', 'bi-bell', 'secondary']; ?>
                <div class="list-group-item d-flex gap-3 align-items-start notif-row <?= $n['is_read'] ? 'read' : '' ?>">
                    <div class="stat-icon sm bg-soft-<?= $m[2] ?>"><i class="bi <?= $m[1] ?>"></i></div>
                    <div class="flex-grow-1 min-w-0">
                        <div class="d-flex align-items-center gap-2"><span class="fw-semibold"><?= e($n['title']) ?></span><?php if (!$n['is_read']): ?><span class="dot-unread"></span><?php endif; ?></div>
                        <div class="small text-muted"><?= e($n['message']) ?></div>
                        <div class="x-small text-muted mt-1"><?= fmt_datetime($n['created_at']) ?> · <?= e($m[0]) ?></div>
                    </div>
                    <div class="d-flex gap-1 flex-shrink-0">
                        <?php if ($n['link']): ?><a href="<?= url($n['link']) ?>" class="btn btn-ghost btn-sm" title="Open"><i class="bi bi-box-arrow-up-right"></i></a><?php endif; ?>
                        <?php if (!$n['is_read']): ?><form method="post"><?= csrf_field() ?><input type="hidden" name="action" value="read"><input type="hidden" name="id" value="<?= $n['id'] ?>"><button class="btn btn-ghost btn-sm" title="Mark read"><i class="bi bi-check2"></i></button></form><?php endif; ?>
                    </div>
                </div>
                <?php endforeach; ?>
            </div>
            <?php endif; ?>
            <?php if ($pages > 1): ?><div class="card-footer bg-transparent"><ul class="pagination pagination-sm mb-0 justify-content-end">
                <li class="page-item <?= $page <= 1 ? 'disabled' : '' ?>"><a class="page-link" href="<?= url($qs(['page' => $page - 1])) ?>">&laquo;</a></li>
                <?php for ($p = max(1, $page - 3); $p <= min($pages, $page + 3); $p++): ?><li class="page-item <?= $p === $page ? 'active' : '' ?>"><a class="page-link" href="<?= url($qs(['page' => $p])) ?>"><?= $p ?></a></li><?php endfor; ?>
                <li class="page-item <?= $page >= $pages ? 'disabled' : '' ?>"><a class="page-link" href="<?= url($qs(['page' => $page + 1])) ?>">&raquo;</a></li></ul></div><?php endif; ?>
        </div>
    </div>
</div>
<?php require ROOT_PATH . '/includes/footer.php'; ?>
